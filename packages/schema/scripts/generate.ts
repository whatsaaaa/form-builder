// Writes the files made from the default registry: definition.schema.json, docs/rules.md and
// docs/field-types.md, and copies the tested renderers from integration/examples into the code
// blocks of docs/frameworks.md. Run it with `pnpm docs:gen`. CI runs it too, and fails when the
// committed files differ, so commit what it writes.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createSchemaBuilder, type FieldTypeDef } from '@whatsaaaa/form-builder-schema'
import { toJsonSchema, type JsonSchema } from '@whatsaaaa/form-builder-schema/json-schema'

type Definition = NonNullable<JsonSchema['properties']>[string]

const builder = createSchemaBuilder()
const schema = toJsonSchema(builder)
const definitions = schema.definitions ?? {}
// The builder knows each type's exact shape. Here every type is read the same way.
const fieldTypes: Readonly<Record<string, FieldTypeDef>> = builder.fieldTypes

const header = (title: string, intro: string) =>
  `<!-- Generated by \`pnpm docs:gen\` from the default registry. Don't edit it by hand. -->\n\n# ${title}\n\n${intro}\n`

write('definition.schema.json', `${JSON.stringify(schema, null, 2)}\n`)
write('docs/rules.md', rulesDoc())
write('docs/field-types.md', fieldTypesDoc())
write('docs/frameworks.md', frameworksDoc())

function write(path: string, content: string): void {
  const url = new URL(`../${path}`, import.meta.url)
  mkdirSync(new URL('.', url), { recursive: true })
  writeFileSync(url, content)
  console.log(`Wrote ${path}`)
}

function rulesDoc(): string {
  const byCategory = new Map<string, string[]>()
  for (const [name, def] of Object.entries(builder.rules)) {
    const category = def.meta?.category ?? 'other'
    const row = [
      code(name),
      def.meta?.label ?? '',
      def.kinds.join(', '),
      ruleParams(name, def.kinds),
      def.meta?.description ?? '',
    ]
    byCategory.set(category, [...(byCategory.get(category) ?? []), tableRow(row)])
  }

  const formRules = Object.entries(builder.formRules).map(([name, def]) =>
    tableRow([
      code(name),
      def.meta?.label ?? '',
      def.kinds?.join(', ') ?? 'any',
      params(pickedBy('formRule', name), ['rule', 'field', 'message']),
      def.meta?.description ?? '',
    ]),
  )

  const head = ['Rule', 'Label', 'Kinds', 'Params', 'Description']
  return [
    header(
      'Rules',
      "Every built-in rule, by category. Params go next to `rule` in a field's `rules`, and every rule also takes a `message`. A rule with params per kind lists them by kind.",
    ),
    ...[...byCategory].map(
      ([category, rows]) => `## ${capitalize(category)}\n\n${table(head, rows)}`,
    ),
    `## Form rules\n\nThese go in \`formRules\`, next to \`fields\`. Each one also takes \`field\`, the path its error shows on, and \`message\`.\n\n${table(head, formRules)}`,
  ].join('\n')
}

function fieldTypesDoc(): string {
  const base = ['name', 'type', 'label', 'description', 'placeholder', 'default', 'required']
  const rows = Object.entries(fieldTypes).map(([name, type]) =>
    tableRow([
      code(name),
      type.meta?.label ?? '',
      kindOf(type),
      params(definitions[`type.${name}`], [...base, 'rules', 'ui']),
      (type.defaultRules ?? []).map((rule) => code(rule.rule)).join(', '),
      type.meta?.description ?? '',
    ]),
  )

  return [
    header(
      'Field types',
      'Every built-in field type. Every field also takes `name`, `label`, `description`, `placeholder`, `default`, `required`, `rules` and `ui`. A type of kind `none` takes no `default`, `required` or `rules`, and a `group` takes no `required` or `default`.',
    ),
    table(['Type', 'Label', 'Kind', 'Props', 'Default rules', 'Description'], rows),
  ].join('\n')
}

/**
 * docs/frameworks.md, with the code block after each `<!-- example: solid/json-form-view.tsx -->`
 * copied from that file in integration/examples. Every file of an example needs a block.
 */
function frameworksDoc(): string {
  const examples = new URL('../../../integration/examples/', import.meta.url)
  const files = readdirSync(examples).flatMap((framework) =>
    readdirSync(new URL(`${framework}/`, examples)).map((file) => `${framework}/${file}`),
  )
  const shown = new Set<string>()
  const doc = readFileSync(new URL('../docs/frameworks.md', import.meta.url), 'utf8').replace(
    /(<!-- example: (\S+) -->\n\n```\w+\n)[\s\S]*?(```)/g,
    (_, open: string, file: string, close: string) => {
      shown.add(file)
      return open + readFileSync(new URL(file, examples), 'utf8') + close
    },
  )
  const missing = files.filter(
    (file) => !file.includes('.test.') && !file.endsWith('tsconfig.json') && !shown.has(file),
  )
  if (missing.length) throw new Error(`docs/frameworks.md has no block for ${missing.join(', ')}`)
  return doc
}

function kindOf(type: FieldTypeDef): string {
  if (typeof type.kind === 'function') return 'from the props'
  if (type.kind !== 'array' || type.itemKind === undefined) return type.kind
  if (typeof type.itemKind === 'function') return 'array, items from the props'
  return `array of ${type.itemKind}`
}

/** A rule's params, by kind when they depend on it. */
function ruleParams(name: string, kinds: readonly string[]): string {
  const skip = ['rule', 'message']
  const single = definitions[`rule.${name}`]
  if (single !== undefined) return params(single, skip)
  return kinds
    .flatMap((kind) => {
      const definition = definitions[`rule.${name}.${kind}`]
      return definition === undefined ? [] : [`${kind}: ${params(definition, skip)}`]
    })
    .join('<br>')
}

/** The schema of one entry of a list picked by name, such as one form rule's. */
function pickedBy(list: string, name: string): Definition | undefined {
  const definition = definitions[list]
  if (typeof definition !== 'object') return undefined
  for (const entry of definition.allOf ?? []) {
    if (typeof entry !== 'object' || typeof entry.then !== 'object') continue
    const rule = entry.then.properties?.rule
    if (typeof rule === 'object' && rule.const === name) return entry.then
  }
  return undefined
}

/** The keys of an object schema besides `skip`, with their types. Optional ones end in `?`. */
function params(definition: Definition | undefined, skip: readonly string[]): string {
  if (typeof definition !== 'object') return ''
  if (!definition.properties) return 'any'
  const required = new Set(definition.required)
  return Object.entries(definition.properties)
    .filter(([key]) => !skip.includes(key))
    .map(([key, value]) => `${code(required.has(key) ? key : `${key}?`)}: ${typeOf(value)}`)
    .join('; ')
}

/** A JSON Schema as a short type, such as `integer, at least 0` or `"lt" | "gt"`. */
function typeOf(definition: Definition | undefined): string {
  if (definition === undefined || definition === true) return 'any'
  if (definition === false) return 'nothing'
  if (definition.$ref === '#/definitions/field' || definition.$ref === '#/definitions/item') {
    return 'field'
  }
  if (definition.const !== undefined) return JSON.stringify(definition.const)
  if (definition.enum) return definition.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (definition.anyOf) return definition.anyOf.map(typeOf).join(' | ')
  if (definition.type === 'array') {
    const items = Array.isArray(definition.items) ? undefined : definition.items
    const item = typeOf(items)
    const list = `${item.includes(' ') ? `(${item})` : item}[]`
    return definition.minItems ? `${list}, at least ${definition.minItems}` : list
  }
  if (definition.type === undefined) return Object.keys(definition).length ? 'object' : 'any'
  const type = Array.isArray(definition.type) ? definition.type.join(' | ') : definition.type
  const { minimum, maximum } = definition
  if (minimum !== undefined && maximum !== undefined) return `${type}, ${minimum} to ${maximum}`
  if (minimum !== undefined) return `${type}, at least ${minimum}`
  if (maximum !== undefined) return `${type}, at most ${maximum}`
  return type
}

function table(head: readonly string[], rows: readonly string[]): string {
  return [tableRow(head), tableRow(head.map(() => '---')), ...rows].join('\n') + '\n'
}

/** A table row. Pipes in cells are escaped, so they don't end the cell. */
function tableRow(cells: readonly string[]): string {
  return `| ${cells.map((cell) => cell.replaceAll('|', '\\|')).join(' | ')} |`
}

function code(text: string): string {
  return `\`${text}\``
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1)
}
